#!/usr/bin/env node
/*
 * Generate a fresh GDEX control wallet, sign in on each chain, and print the
 * managed-custody deposit addresses the user must fund. Secrets are written to
 * a chmod-600 file OUTSIDE any git repo. Never commit the output file.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { ethers } = require('ethers');
const {
  GdexSkill,
  GDEX_API_KEY_PRIMARY,
  generateEvmWallet,
  generateGdexSessionKeyPair,
  generateGdexNonce,
  buildGdexSignInMessage,
  buildGdexSignInComputedData,
} = require('../../dist');

const CHAINS = [
  { name: 'Solana', chainId: 622112261, fund: 'SOL (native) + SPL tokens' },
  { name: 'Arbitrum (HyperLiquid)', chainId: 42161, fund: 'USDC on Arbitrum for perps' },
  { name: 'Base', chainId: 8453, fund: 'ETH on Base for EVM spot/limit' },
];

async function main() {
  const apiKey = GDEX_API_KEY_PRIMARY;
  const w = generateEvmWallet();
  const controlAddr = w.address;
  const wallet = new ethers.Wallet(w.privateKey);

  const skill = new GdexSkill({ timeout: 45000, maxRetries: 1 });
  skill.loginWithApiKey(apiKey);

  const managed = {};
  for (const c of CHAINS) {
    try {
      const kp = generateGdexSessionKeyPair();
      const nonce = generateGdexNonce().toString();
      const msg = buildGdexSignInMessage(controlAddr, nonce, kp.sessionKey);
      const sig = await wallet.signMessage(msg);
      const payload = buildGdexSignInComputedData({
        apiKey, userId: controlAddr, sessionKey: kp.sessionKey, nonce,
        signature: sig.replace(/^0x/, ''),
      });
      const resp = await skill.signInWithComputedData({ computedData: payload.computedData, chainId: c.chainId });
      managed[c.name] = { chainId: c.chainId, address: resp.address || resp.walletAddress || null, fund: c.fund, sessionPrivateKey: kp.sessionPrivateKey };
    } catch (e) {
      managed[c.name] = { chainId: c.chainId, address: null, error: e.message, fund: c.fund };
    }
  }

  const secretsPath = path.join(os.homedir(), 'gdex-test-wallet.json');
  fs.writeFileSync(secretsPath, JSON.stringify({
    createdAt: new Date().toISOString(),
    control: { address: controlAddr, privateKey: w.privateKey, mnemonic: w.mnemonic || null },
    managed,
  }, null, 2));
  fs.chmodSync(secretsPath, 0o600);

  console.log('\n=== GDEX TEST WALLET (generated by the skill) ===');
  console.log('Control wallet (your identity / userId):', controlAddr);
  console.log('Secrets written to:', secretsPath, '(chmod 600)');
  console.log('\n--- FUND THESE MANAGED DEPOSIT ADDRESSES ---');
  for (const [name, m] of Object.entries(managed)) {
    console.log(`\n${name} (chainId ${m.chainId})`);
    console.log(`  deposit address : ${m.address || 'ERROR: ' + m.error}`);
    console.log(`  fund with       : ${m.fund}`);
  }
  console.log('\nAfter funding, trades run through THIS wallet (control = userId, managed = holds funds).');
}

main().catch(e => { console.error('FATAL', e.message); process.exit(1); });
